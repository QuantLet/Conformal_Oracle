"""Manuscript displays of the ten-support benchmark study.

Reads artifacts/r8_ten_benchmarks/{summary.csv, metrics.csv, run.json} and the ten-model summary.csv; writes source/sections_r8/{numbers_ten_benchmarks,tab_ten_benchmarks}.tex. --check compares.
"""
import argparse, hashlib, json, sys
from pathlib import Path
import pandas as pd
ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'artifacts/r8_ten_benchmarks'; OUT = ROOT / 'source/sections_r8'
NATIVE = ROOT / 'artifacts/r8_model_extension/ten_common_evaluation/summary.csv'
CLASSICAL = ['GJR-GARCH', 'GJR-GARCH-t', 'GARCH-N', 'Hist-Sim', 'EWMA']; LABELS = {'GJR-GARCH': 'GJR-N', 'GJR-GARCH-t': 'GJR-$t$', 'Hist-Sim': 'Historical simulation'}
ROWS = [('CAViaR-SAV', 'Sav', 'CAViaR-SAV'), ('CAViaR-AS', 'As', 'CAViaR-AS'), ('GAS-t', 'Gas', 'GAS-$t$'), ('EVT-POT', 'Pot', 'EVT-POT'), ('FHS', 'Fhs', 'FHS')]

def build():
    s = pd.read_csv(ART / 'summary.csv').set_index(['model', 'method']); run = json.loads((ART / 'run.json').read_text())['summary']
    m = {'Assets': str(run['assets']), 'TestObs': f"{run['test_observations']:,}", 'PreTestMin': str(run['pre_test_min']), 'PreTestMax': str(run['pre_test_max']),
         'InsideFitShareMin': f"{100 * run['calibration_inside_fit_share_min']:.1f}", 'InsideFitShareMax': f"{100 * run['calibration_inside_fit_share_max']:.1f}",
         'TestAfterFit': str(run['assets']) if run['test_after_fit_all'] else 'FAIL', 'Shared': str(run['shared_series']), 'SharedIdentical': str(run['shared_support_identical']),
         'Replaced': ', '.join(run['replaced_series'])}
    unavailable = 0
    lines = [r'\begingroup\setlength{\tabcolsep}{3.5pt}', r'\begin{tabular}{lrrrrrrr}', r'\toprule',
             r'Forecaster & QS raw & QS static & QS rolling & $\pi$ raw & $\pi$ static & UC & Ind. \\', r'\midrule']
    for model, tag, label in ROWS:
        raw = s.loc[(model, 'Raw')]; assert raw.assets == 24
        m[tag + 'RawQS'] = f'{raw.QS_x10000:.4f}'; m[tag + 'RawPi'] = f'{raw.pi_mean * 100:.3f}'; m[tag + 'RawKup'] = str(int(raw.kupiec_rejections)); m[tag + 'RawInd'] = str(int(raw.independence_rejections))
        m[tag + 'RawIndAvail'] = str(int(raw.independence_available)); unavailable += 24 - int(raw.independence_available)
        if (model, 'Static') in s.index:
            stat = s.loc[(model, 'Static')]; roll = s.loc[(model, 'Rolling250')]; assert stat.independence_available == 24 and roll.independence_available == 24
            m[tag + 'StaticQS'] = f'{stat.QS_x10000:.4f}'; m[tag + 'RollingQS'] = f'{roll.QS_x10000:.4f}'; m[tag + 'StaticPi'] = f'{stat.pi_mean * 100:.3f}'; m[tag + 'RollingPi'] = f'{roll.pi_mean * 100:.3f}'
            m[tag + 'StaticKup'] = str(int(stat.kupiec_rejections)); m[tag + 'StaticInd'] = str(int(stat.independence_rejections)); m[tag + 'RollingKup'] = str(int(roll.kupiec_rejections))
            lines.append(f'{label} & {raw.QS_x10000:.4f} & {stat.QS_x10000:.4f} & {roll.QS_x10000:.4f} & {raw.pi_mean * 100:.3f} & {stat.pi_mean * 100:.3f} & '
                         f'{int(raw.kupiec_rejections)}/{int(stat.kupiec_rejections)} & {int(raw.independence_rejections)}/{int(stat.independence_rejections)}' + r' \\')
        else:
            lines.append(f'{label} & {raw.QS_x10000:.4f} & -- & -- & {raw.pi_mean * 100:.3f} & -- & {int(raw.kupiec_rejections)}/-- & {int(raw.independence_rejections)}/--' + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\endgroup']
    ten = pd.read_csv(NATIVE); assert len(ten) == 30 and (ten.assets == 24).all()
    for method, tag in [('Raw', 'Raw'), ('Static', 'Static')]:
        g = ten[ten.method == method].set_index('model'); best = g.QS_x10000.idxmin(); m[f'TenBest{tag}QS'] = f'{g.QS_x10000.min():.4f}'; m[f'TenBest{tag}Model'] = LABELS.get(best, best)
        c = g.loc[CLASSICAL]; bestc = c.QS_x10000.idxmin(); m[f'TenBestClassical{tag}QS'] = f'{c.QS_x10000.min():.4f}'; m[f'TenBestClassical{tag}Model'] = LABELS.get(bestc, bestc)
    static = ten[ten.method == 'Static'].set_index('model').QS_x10000
    for model, tag, _ in ROWS[3:]:
        raw = s.loc[(model, 'Raw')].QS_x10000; above = static[static > raw]; below = static[static <= raw]
        m[tag + 'StaticAboveCount'] = str(len(above)); m[tag + 'StaticBelowModels'] = ', '.join(LABELS.get(x, x) for x in below.index) or 'none'
    zero = pd.read_csv(ART / 'metrics.csv'); zero = zero[zero.p_ind.isna()]; assert len(zero) == unavailable
    m['IndUnavailable'] = str(unavailable); m['IndUnavailableCells'] = '; '.join(f'{r.model} raw on {r.asset}' for r in zero.itertuples()) or 'none'
    head = '% Generated by research/r8_ten_benchmarks/displays.py; do not edit.\n'
    num = head + ''.join(f'\\newcommand{{\\nTenBench{k}}}{{{v}}}\n' for k, v in m.items())
    return num, head + '\n'.join(lines) + '\n'

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true'); a = ap.parse_args()
    num, tab = build(); targets = {OUT / 'numbers_ten_benchmarks.tex': num, OUT / 'tab_ten_benchmarks.tex': tab}
    if a.check:
        bad = [str(p) for p, t in targets.items() if not p.exists() or p.read_text() != t]
        print(json.dumps(dict(status='pass' if not bad else 'FAIL', stale=bad))); sys.exit(1 if bad else 0)
    for p, t in targets.items(): p.write_text(t)
    rec = dict(inputs={n: hashlib.sha256((ART / n).read_bytes()).hexdigest() for n in ['summary.csv', 'metrics.csv', 'run.json']} | {'ten_summary.csv': hashlib.sha256(NATIVE.read_bytes()).hexdigest()},
               outputs={p.name: hashlib.sha256(t.encode()).hexdigest() for p, t in targets.items()})
    (ART / 'displays.json').write_text(json.dumps(rec, indent=2) + '\n'); print('written')
if __name__ == '__main__': main()
